#!/usr/bin/env python3
"""Generates esp32/LDToyPadEmulator/CatalogData.h from the web UI's
server/json/charactermap.json and server/json/tokenmap.json, so the firmware
does not have to parse these files at runtime.

Run from anywhere after changing one of the JSON files:
    python3 esp32/tools/generate_catalog.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "esp32" / "LDToyPadEmulator" / "CatalogData.h"
MAX_NAME_LENGTH = 40


def c_string(text):
    # The firmware embeds the names in JSON without escaping them.
    if not text.isascii() or any(c in text for c in '"\\') or not text.isprintable():
        raise ValueError(f"Unsupported character in name: {text!r}")
    # TagStore renders one JSON record into a 128 byte buffer
    if len(text) > MAX_NAME_LENGTH:
        raise ValueError(f"Name longer than {MAX_NAME_LENGTH} characters: {text!r}")
    return json.dumps(text)  # ASCII JSON string literals are valid C string literals


def table(name, path):
    entries = sorted(json.loads(path.read_text(encoding="utf-8")), key=lambda e: e["id"])
    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        raise ValueError(f"Duplicate ids in {path}")
    rows = "\n".join(f"    {{{e['id']}, {c_string(e['name'])}}}," for e in entries)
    return f"static const CatalogEntry {name}[] = {{\n{rows}\n}};\n"


def main():
    json_dir = ROOT / "server" / "json"
    OUTPUT.write_text(
        "// Generated by esp32/tools/generate_catalog.py from server/json/charactermap.json\n"
        "// and server/json/tokenmap.json - do not edit.\n"
        "// Constant data is placed in flash (DROM) on the ESP32, it does not use RAM.\n\n"
        "#pragma once\n\n"
        '#include "Catalog.h"\n\n'
        "namespace ld {\n\n"
        + table("CHARACTERS", json_dir / "charactermap.json")
        + "\n"
        + table("VEHICLES", json_dir / "tokenmap.json")
        + "\n} // namespace ld\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
